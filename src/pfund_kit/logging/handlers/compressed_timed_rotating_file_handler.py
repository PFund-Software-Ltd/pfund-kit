import gzip
import os
import time
from logging.handlers import TimedRotatingFileHandler
from typing import override


class CompressedTimedRotatingFileHandler(TimedRotatingFileHandler):
    # Opens the rotated log file, compresses it to .gz, then deletes the original
    def gzip_logs(self, file_path):
        gz_path = f"{file_path}.gz"
        try:
            with open(file_path, "rb") as f_in, gzip.open(gz_path, "wb") as f_out:
                f_out.writelines(f_in)
            os.remove(file_path)
        except Exception:
            # If gzip failed, clean up partial .gz file
            if os.path.exists(gz_path):
                os.remove(gz_path)
            raise

    # NOTE: copied code from TimedRotatingFileHandler getFilesToDelete()
    # override the method in TimedRotatingFileHandler because after gzipping, the pattern in the original function no longer works
    @override
    def getFilesToDelete(self):
        """
        Determine the files to delete when rolling over.
        More specific than the earlier method, which just used glob.glob().
        """
        dir_name, base_name = os.path.split(self.baseFilename)
        file_names = os.listdir(dir_name)
        result = []
        if self.namer is None:
            prefix = base_name + "."
            plen = len(prefix)
            for file_name in file_names:
                orig_filename = file_name
                # Remove .gz extension if present for pattern matching
                file_name = file_name[:-3] if file_name.endswith(".gz") else file_name
                if file_name[:plen] == prefix:
                    suffix = file_name[plen:]
                    if self.extMatch.fullmatch(suffix):
                        result.append(os.path.join(dir_name, orig_filename))
        else:
            for file_name in file_names:
                orig_filename = file_name
                # Remove .gz extension if present for pattern matching
                file_name = file_name[:-3] if file_name.endswith(".gz") else file_name
                # Our files could be just about anything after custom naming,
                # but they should contain the datetime suffix.
                # Try to find the datetime suffix in the file name and verify
                # that the file name can be generated by this handler.
                m = self.extMatch.search(file_name)
                while m:
                    dfn = self.namer(self.baseFilename + "." + m[0])
                    if os.path.basename(dfn) == file_name:
                        result.append(os.path.join(dir_name, orig_filename))
                        break
                    m = self.extMatch.search(file_name, m.start() + 1)

        if len(result) < self.backupCount:
            result = []
        else:
            result.sort()
            result = result[: len(result) - self.backupCount]
        return result

    # NOTE: copied code from TimedRotatingFileHandler doRollover()
    # used to get the dfn (destination filename) and pass it to gzip_logs()
    @override
    def doRollover(self):
        # get the time that this sequence started at and make it a TimeTuple
        current_time = int(time.time())
        t = self.rolloverAt - self.interval
        if self.utc:
            time_tuple = time.gmtime(t)
        else:
            time_tuple = time.localtime(t)
            # dst = daylight saving time
            dst_now = time.localtime(current_time)[-1]
            dst_then = time_tuple[-1]
            if dst_now != dst_then:
                addend = 3600 if dst_now else -3600
                time_tuple = time.localtime(t + addend)
        # dfn = destination filename
        dfn = self.rotation_filename(
            self.baseFilename + "." + time.strftime(self.suffix, time_tuple)
        )
        if os.path.exists(dfn):
            # Already rolled over.
            return

        if self.stream:
            self.stream.close()
            self.stream = None
        self.rotate(self.baseFilename, dfn)
        if self.backupCount > 0:
            for s in self.getFilesToDelete():
                os.remove(s)
        if not self.delay:
            self.stream = self._open()
        self.rolloverAt = self.computeRollover(current_time)

        # compress the log file
        self.gzip_logs(dfn)
